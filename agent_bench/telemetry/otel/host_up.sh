#!/usr/bin/env bash
# Start otelcol-contrib as a host process (no docker). Idempotent.
#
# Downloads the binary on first run into ~/.cache/oc-agent_bench/telemetry/otelcol/
# if not already present. Writes a per-run collector config so the file exporter
# follows AB_TELEMETRY_TRACE_FILE.
#
# Env:
#   AB_TELEMETRY_VERSION    collector release tag (default: v0.115.1)
#   AB_TELEMETRY_DATA_DIR   collector config/log/pid dir (default: /tmp/otel)
#   AB_TELEMETRY_TRACE_FILE trace output path (default: $AB_TELEMETRY_DATA_DIR/otel-traces.jsonl)
#   AB_TELEMETRY_PORT       OTLP/HTTP port (default: 4318)
#   AB_TELEMETRY_GRPC_PORT  OTLP/gRPC port (default: 4317)
#   AB_TELEMETRY_CONFIG     explicit config file (otherwise generated in DATA_DIR)

set -euo pipefail

AB_REPO_ROOT="${AB_REPO_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)}"
VERSION="${AB_TELEMETRY_VERSION:-v0.115.1}"
DATA_DIR="${AB_TELEMETRY_DATA_DIR:-/tmp/otel}"
TRACE_FILE="${AB_TELEMETRY_TRACE_FILE:-$DATA_DIR/otel-traces.jsonl}"
PORT="${AB_TELEMETRY_PORT:-4318}"
GRPC_PORT="${AB_TELEMETRY_GRPC_PORT:-4317}"
CONFIG="${AB_TELEMETRY_CONFIG:-$DATA_DIR/otelcol.yaml}"
CACHE="${AB_TELEMETRY_CACHE:-$HOME/.cache/oc-agent_bench/telemetry/otelcol}"

mkdir -p "$DATA_DIR" "$(dirname "$TRACE_FILE")" "$CACHE"
touch "$TRACE_FILE"

if [ -z "${AB_TELEMETRY_CONFIG:-}" ]; then
    cat > "$CONFIG" <<YAML
# Generated by host_up.sh -- overwritten on every start.
receivers:
  otlp:
    protocols:
      grpc:
        endpoint: 127.0.0.1:$GRPC_PORT
      http:
        endpoint: 127.0.0.1:$PORT

exporters:
  file:
    path: $TRACE_FILE

service:
  telemetry:
    logs:
      level: warn
  pipelines:
    traces:
      receivers: [otlp]
      exporters: [file]
    metrics:
      receivers: [otlp]
      exporters: [file]
    logs:
      receivers: [otlp]
      exporters: [file]
YAML
fi

if [ ! -f "$CONFIG" ]; then
    echo "[otel-up-host] config missing: $CONFIG" >&2
    exit 1
fi

PID_FILE="$DATA_DIR/otelcol.pid"
LOG_FILE="$DATA_DIR/otelcol.log"

# Already running?
if [ -f "$PID_FILE" ] && kill -0 "$(cat "$PID_FILE")" 2>/dev/null; then
    echo "[otel-up-host] already running (pid $(cat "$PID_FILE"))" >&2
    exit 0
fi

# Detect platform.
case "$(uname -s)" in
    Linux)  OS=linux ;;
    Darwin) OS=darwin ;;
    *) echo "[otel-up-host] unsupported OS: $(uname -s)" >&2; exit 1 ;;
esac
case "$(uname -m)" in
    x86_64|amd64) ARCH=amd64 ;;
    aarch64|arm64) ARCH=arm64 ;;
    *) echo "[otel-up-host] unsupported arch: $(uname -m)" >&2; exit 1 ;;
esac

BIN="$CACHE/otelcol-contrib-${VERSION}-${OS}-${ARCH}"
if [ ! -x "$BIN" ]; then
    URL="https://github.com/open-telemetry/opentelemetry-collector-releases/releases/download/${VERSION}/otelcol-contrib_${VERSION#v}_${OS}_${ARCH}.tar.gz"
    echo "[otel-up-host] downloading $URL" >&2
    TMP=$(mktemp -d)
    curl -fsSL "$URL" -o "$TMP/otelcol.tar.gz"
    tar -xzf "$TMP/otelcol.tar.gz" -C "$TMP"
    mv "$TMP/otelcol-contrib" "$BIN"
    chmod +x "$BIN"
    rm -rf "$TMP"
fi

# Bail early if anything else already binds the OTLP ports.
for p in "$GRPC_PORT" "$PORT"; do
    if ss -tln "( sport = :$p )" 2>/dev/null | grep -q LISTEN; then
        echo "[otel-up-host] port $p already in use (another collector running?)" >&2
        ss -tlnp 2>/dev/null | grep ":$p " >&2 || true
        exit 1
    fi
done

echo "[otel-up-host] starting $BIN (config=$CONFIG, traces=$TRACE_FILE)" >&2
nohup "$BIN" --config "$CONFIG" > "$LOG_FILE" 2>&1 &
PID=$!
echo "$PID" > "$PID_FILE"

# Poll readiness: collector logs "Everything is ready. Begin running and processing data."
for i in $(seq 1 30); do
    if ! kill -0 "$PID" 2>/dev/null; then
        echo "[otel-up-host] collector exited early; tail of $LOG_FILE:" >&2
        tail -30 "$LOG_FILE" >&2
        rm -f "$PID_FILE"
        exit 2
    fi
    if grep -q "Everything is ready" "$LOG_FILE" 2>/dev/null; then
        echo "[otel-up-host] ready (pid $PID) after ${i}s" >&2
        exit 0
    fi
    sleep 1
done

echo "[otel-up-host] collector did not become ready in 30s; tail of $LOG_FILE:" >&2
tail -30 "$LOG_FILE" >&2
exit 2
