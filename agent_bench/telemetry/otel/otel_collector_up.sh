#!/usr/bin/env bash
# Start the OTel collector container that OpenClaw gateways export to.
#
# Idempotent: does nothing if a container named AB_TELEMETRY_NAME already runs.
# Writes a per-run collector config so AB_TELEMETRY_TRACE_FILE can live under the
# active experiment log directory instead of the historical /tmp/otel path.

set -euo pipefail

AB_REPO_ROOT="${AB_REPO_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)}"
NAME="${AB_TELEMETRY_NAME:-oc-otel}"
IMAGE="${AB_TELEMETRY_IMAGE:-otel/opentelemetry-collector-contrib:latest}"
DATA_DIR="${AB_TELEMETRY_DATA_DIR:-/tmp/otel}"
TRACE_FILE="${AB_TELEMETRY_TRACE_FILE:-$DATA_DIR/otel-traces.jsonl}"
PORT="${AB_TELEMETRY_PORT:-4318}"
GRPC_PORT="${AB_TELEMETRY_GRPC_PORT:-4317}"
TRACE_DIR="$(dirname "$TRACE_FILE")"
TRACE_BASENAME="$(basename "$TRACE_FILE")"
CONFIG_FILE="$DATA_DIR/otelcol.yaml"

mkdir -p "$DATA_DIR" "$TRACE_DIR"
chmod 777 "$DATA_DIR" "$TRACE_DIR" 2>/dev/null || true
touch "$TRACE_FILE"
chmod 666 "$TRACE_FILE" 2>/dev/null || true

cat > "$CONFIG_FILE" <<YAML
# Generated by otel_collector_up.sh -- overwritten on every start.
receivers:
  otlp:
    protocols:
      grpc:
        endpoint: 0.0.0.0:$GRPC_PORT
      http:
        endpoint: 0.0.0.0:$PORT

exporters:
  file:
    path: /data/$TRACE_BASENAME

service:
  telemetry:
    logs:
      level: warn
  pipelines:
    traces:
      receivers: [otlp]
      exporters: [file]
    metrics:
      receivers: [otlp]
      exporters: [file]
    logs:
      receivers: [otlp]
      exporters: [file]
YAML

if docker ps --format '{{.Names}}' | grep -qx "$NAME"; then
    echo "[otel-up] $NAME already running" >&2
    exit 0
fi
# If a stopped container with same name exists, remove it.
if docker ps -a --format '{{.Names}}' | grep -qx "$NAME"; then
    docker rm -f "$NAME" >/dev/null
fi

echo "[otel-up] starting $NAME (image=$IMAGE, traces=$TRACE_FILE)" >&2
docker run -d --name "$NAME" --network host \
    -v "$CONFIG_FILE:/etc/otelcol-contrib/config.yaml:ro" \
    -v "$TRACE_DIR:/data:rw" \
    "$IMAGE" --config /etc/otelcol-contrib/config.yaml >/dev/null

# Poll for readiness (HTTP receiver on :$PORT).
for i in $(seq 1 30); do
    if curl -fsS -o /dev/null -X POST -H 'Content-Type: application/json' \
        --data '{}' "http://127.0.0.1:$PORT/v1/traces" 2>/dev/null; then
        echo "[otel-up] ready after ${i}s" >&2
        exit 0
    fi
    if ! docker ps --format '{{.Names}}' | grep -qx "$NAME"; then
        echo "[otel-up] collector exited during startup" >&2
        docker logs --tail 30 "$NAME" >&2 || true
        exit 2
    fi
    sleep 1
done
echo "[otel-up] OTel collector did not become ready in 30s" >&2
docker logs --tail 30 "$NAME" >&2 || true
exit 2
