from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
import json
import os
from pathlib import Path
import re
import shlex
from typing import Any, Mapping
from zoneinfo import ZoneInfo

from agent_bench.core.spec import ConfigError, ResolvedExperiment, STAGE_NAMES
from agent_bench.serving.launch_plan import LaunchPlanError, ServingLaunchPlan, build_launch_plan


RUNTIME_STAGES = STAGE_NAMES

_LEGACY_STAGE_ENV = {
    "materialize_benchmark": ("STAGE_SWEBENCH", "STAGE_TB_DATA"),
    "prepare_images": ("STAGE_PULL", "STAGE_TB_PULL"),
    "start_serving": ("STAGE_SERVING",),
    "start_otel": ("STAGE_OTEL",),
    "run_benchmark": ("STAGE_RUN",),
    "cleanup": ("STAGE_CLEANUP",),
}


@dataclass(frozen=True)
class PbsResources:
    job_name: str
    queue: str | None
    walltime: str
    nodes: int
    cpus: int | None
    gpus: int
    memory: str | None
    join_output: bool = True

    def select_value(self) -> str:
        parts = [f"select={self.nodes}"]
        if self.cpus is not None:
            parts.append(f"ncpus={self.cpus}")
        if self.gpus > 0:
            parts.append(f"ngpus={self.gpus}")
        if self.memory:
            parts.append(f"mem={self.memory}")
        return ":".join(parts)


@dataclass(frozen=True)
class PbsJobSpec:
    site: str
    experiment_name: str
    config_path: Path
    resources: PbsResources
    stages: dict[str, bool]
    run_dir: Path
    log_dir: Path
    scratch_dir: str
    container_runtime: str
    serving_plan: ServingLaunchPlan | None = None
    warnings: tuple[str, ...] = ()
    metadata: dict[str, str] = field(default_factory=dict)

    def render_script(self) -> str:
        config_arg = _shell_path(self.config_path)
        lines = [
            "#!/usr/bin/env bash",
            f"# Generated by Agent Bench PBS renderer for {self.site}.",
            f"#PBS -N {self.resources.job_name}",
            f"#PBS -l {self.resources.select_value()}",
            f"#PBS -l walltime={self.resources.walltime}",
        ]
        if self.resources.queue:
            lines.append(f"#PBS -q {self.resources.queue}")
        if self.resources.join_output:
            lines.append("#PBS -j oe")
        experiment_base = self.run_dir.parent
        lines.extend(
            [
                "",
                "set -euo pipefail",
                'cd "${PBS_O_WORKDIR:-$PWD}"',
                f"export AGENT_BENCH_PBS_SITE={shlex.quote(self.site)}",
                'if [[ -z "${AB_RUN_STAMP:-}" ]]; then',
                '    AB_RUN_STAMP="$(TZ=Asia/Singapore date +%Y-%m-%d_%H-%M-%S)"',
                '    if [[ -n "${PBS_JOBID:-}" ]]; then',
                '        AB_JOB_SUFFIX="${PBS_JOBID//[^A-Za-z0-9._-]/_}"',
                '        AB_RUN_STAMP="${AB_RUN_STAMP}_${AB_JOB_SUFFIX}"',
                "    fi",
                "fi",
                "export AB_RUN_STAMP",
                f"export AB_EXPERIMENT_BASE={shlex.quote(str(experiment_base))}",
                'export AB_EXPERIMENT_DIR="${AB_EXPERIMENT_DIR:-$AB_EXPERIMENT_BASE/$AB_RUN_STAMP}"',
                'export AGENT_BENCH_RUN_DIR="${AGENT_BENCH_RUN_DIR:-$AB_EXPERIMENT_DIR}"',
                'export AGENT_BENCH_LOG_DIR="${AGENT_BENCH_LOG_DIR:-$AGENT_BENCH_RUN_DIR/logs}"',
                f"export AGENT_BENCH_STAGES={shlex.quote(self.stage_summary())}",
                f"python3 run.py --config {config_arg}",
                "",
            ]
        )
        return "\n".join(lines)

    def stage_summary(self) -> str:
        return ",".join(f"{stage}={int(self.stages[stage])}" for stage in RUNTIME_STAGES)

    def to_redacted_dict(self) -> dict[str, Any]:
        return {
            "site": self.site,
            "experiment_name": self.experiment_name,
            "config_path": str(self.config_path),
            "resources": {
                "job_name": self.resources.job_name,
                "queue": self.resources.queue,
                "walltime": self.resources.walltime,
                "nodes": self.resources.nodes,
                "cpus": self.resources.cpus,
                "gpus": self.resources.gpus,
                "memory": self.resources.memory,
                "join_output": self.resources.join_output,
            },
            "stages": dict(self.stages),
            "run_dir": str(self.run_dir),
            "log_dir": str(self.log_dir),
            "scratch_dir": self.scratch_dir,
            "container_runtime": self.container_runtime,
            "serving_plan": self.serving_plan.to_redacted_dict() if self.serving_plan else None,
            "warnings": list(self.warnings),
            "metadata": dict(self.metadata),
        }


def build_pbs_job_spec(
    resolved: ResolvedExperiment,
    *,
    site: str = "NSCC",
    env: Mapping[str, str] | None = None,
    repo_root: str | Path | None = None,
) -> PbsJobSpec:
    source_env = dict(os.environ if env is None else env)
    root = Path(repo_root or source_env.get("KIT_ROOT") or Path.cwd()).resolve()
    deployment = resolved.deployment
    backend = resolved.serving.get("backend")
    scratch = _env_str(source_env, "SCRATCH", default=str(Path.home() / "scratch"))
    run_stamp, run_dir = _resolve_job_run_dir(resolved, source_env)
    log_dir = _path_from_env_or_default(source_env, "AGENT_BENCH_LOG_DIR", run_dir / "logs")

    resources = PbsResources(
        job_name=_env_str(source_env, "PBS_JOB_NAME", default=deployment.get("job_name") or f"agent-bench-{resolved.spec.name}"),
        queue=_env_optional(source_env, "PBS_QUEUE", default=deployment.get("queue")),
        walltime=_env_str(source_env, "PBS_WALLTIME", default=deployment.get("walltime", "02:00:00")),
        nodes=_env_int(source_env, "PBS_NODES", default=int(deployment.get("nodes", 1))),
        cpus=_env_optional_int(source_env, "PBS_CPUS", default=deployment.get("cpus") or deployment.get("ncpus")),
        gpus=_env_int(source_env, "PBS_GPUS", "NGPUS", default=int(deployment.get("gpus", 0))),
        memory=_env_optional(source_env, "PBS_MEMORY", default=deployment.get("memory") or deployment.get("mem")),
        join_output=_env_bool(source_env, "PBS_JOIN_OUTPUT", default=bool(deployment.get("join_output", True))),
    )
    stages = _resolve_stages(resolved, source_env)

    serving_plan: ServingLaunchPlan | None = None
    warnings: list[str] = []
    if backend in {"vllm", "sglang", "litellm"}:
        mode = _serving_mode(resolved, source_env)
        try:
            serving_plan = build_launch_plan(
                model_path=resolved.profile_paths["model"],
                serving_path=resolved.profile_paths["serving"],
                backend=str(backend),
                mode=mode,
                env={**source_env, "KIT_ROOT": str(root)},
                log_path=log_dir / f"{backend}.log",
            )
        except LaunchPlanError as exc:
            warnings.append(f"serving launch plan not complete: {exc}")

    return PbsJobSpec(
        site=site,
        experiment_name=resolved.spec.name,
        config_path=resolved.spec.config_path,
        resources=resources,
        stages=stages,
        run_dir=run_dir,
        log_dir=log_dir,
        scratch_dir=scratch,
        container_runtime=str(deployment.get("container_runtime", "singularity")),
        serving_plan=serving_plan,
        warnings=tuple(warnings),
        metadata={
            "benchmark": resolved.spec.benchmark_name,
            "harness": resolved.spec.harness_name,
            "serving_backend": str(backend),
            "run_id": resolved.run_id,
            "run_stamp": run_stamp,
            "stable_run_id": resolved.run_id,
        },
    )


def _resolve_stages(resolved: ResolvedExperiment, env: Mapping[str, str]) -> dict[str, bool]:
    deployment_stages = resolved.deployment.get("stages") or {}
    if not isinstance(deployment_stages, dict):
        raise ConfigError("deployment.stages must be a table/object when present")
    experiment_stages = resolved.spec.stages
    stages = {stage: True for stage in RUNTIME_STAGES}
    if resolved.serving.get("backend") not in {"vllm", "sglang", "litellm"}:
        stages["start_serving"] = False
    for stage in RUNTIME_STAGES:
        if stage in deployment_stages:
            stages[stage] = bool(deployment_stages[stage])
        if stage in experiment_stages:
            stages[stage] = experiment_stages[stage]
        new_key = f"AB_STAGE_{stage.upper()}"
        if new_key in env:
            stages[stage] = _parse_bool(env[new_key])
        for old_key in _LEGACY_STAGE_ENV.get(stage, ()):
            if old_key in env:
                stages[stage] = _parse_bool(env[old_key])
                break
    return stages


def _serving_mode(resolved: ResolvedExperiment, env: Mapping[str, str]) -> str:
    explicit = env.get("SERVING_MODE")
    if explicit:
        return explicit
    backend = resolved.serving.get("backend")
    backend_key = f"{str(backend).upper()}_MODE"
    if backend_key in env:
        return env[backend_key]
    if resolved.deployment.get("container_runtime") == "singularity":
        return "singularity"
    return "native"


def _path_from_env_or_default(env: Mapping[str, str], key: str, default: str | Path) -> Path:
    value = env.get(key)
    if value:
        return Path(value).expanduser()
    return Path(default).expanduser()


def _resolve_job_run_dir(
    resolved: ResolvedExperiment,
    env: Mapping[str, str],
) -> tuple[str, Path]:
    explicit = env.get("AGENT_BENCH_RUN_DIR")
    if explicit:
        run_dir = Path(explicit).expanduser()
        return run_dir.name, run_dir

    experiment_dir = env.get("AB_EXPERIMENT_DIR")
    if experiment_dir:
        run_dir = Path(experiment_dir).expanduser()
        return run_dir.name, run_dir

    stamp = _run_stamp(env)
    return stamp, resolved.spec.output_dir / stamp


def _run_stamp(env: Mapping[str, str]) -> str:
    explicit = env.get("AB_RUN_STAMP")
    if explicit:
        return explicit
    stamp = datetime.now(ZoneInfo("Asia/Singapore")).strftime("%Y-%m-%d_%H-%M-%S")
    job_id = env.get("PBS_JOBID")
    if job_id:
        stamp = f"{stamp}_{_sanitize_run_stamp_suffix(job_id)}"
    return stamp


def _sanitize_run_stamp_suffix(value: str) -> str:
    return re.sub(r"[^A-Za-z0-9._-]", "_", value)


def _shell_path(path: Path) -> str:
    try:
        value = str(path.relative_to(Path.cwd()))
    except ValueError:
        value = str(path)
    return shlex.quote(value)


def _env_str(env: Mapping[str, str], *keys: str, default: Any) -> str:
    for key in keys:
        value = env.get(key)
        if value not in (None, ""):
            return str(value)
    return str(default)


def _env_optional(env: Mapping[str, str], *keys: str, default: Any = None) -> str | None:
    for key in keys:
        value = env.get(key)
        if value not in (None, ""):
            return str(value)
    if default in (None, ""):
        return None
    return str(default)


def _env_int(env: Mapping[str, str], *keys: str, default: int) -> int:
    return int(_env_str(env, *keys, default=default))


def _env_optional_int(env: Mapping[str, str], *keys: str, default: Any = None) -> int | None:
    value = _env_optional(env, *keys, default=default)
    return int(value) if value is not None else None


def _env_bool(env: Mapping[str, str], *keys: str, default: bool) -> bool:
    for key in keys:
        if key in env:
            return _parse_bool(env[key])
    return default


def _parse_bool(value: Any) -> bool:
    if isinstance(value, bool):
        return value
    return str(value).strip().lower() not in {"0", "false", "no", "off", ""}


def dump_spec_json(spec: PbsJobSpec) -> str:
    return json.dumps(spec.to_redacted_dict(), indent=2, sort_keys=True)
