#!/bin/bash
# Start/stop a local OTel collector for the OC gateway.
#
# The OC gateway emits OTLP/HTTP spans + metrics + logs to
# http://localhost:$PORT (configured in frontend/openclaw/state/openclaw.json →
# diagnostics.otel.endpoint). Without a collector listening, every span is
# dropped on the floor and `data/runs/<run>/spans.jsonl` is never produced
# (it's a slice of the collector's on-disk trace file —
# eval/conditions/code_agent/openclaw_agent.py:_snapshot_otel_spans).
#
# This script runs `otel/opentelemetry-collector-contrib` via singularity
# with a config that has just one OTLP/HTTP receiver and a `file` exporter
# pointing at $OC_OTEL_DATA_DIR/otel-traces.jsonl. Best-effort — failures
# log a warning and exit non-zero so the caller can decide whether to abort
# the whole run or proceed without telemetry.
#
# Usage:
#   pbs/otel_collector.sh start   # writes pid file + tail log
#   pbs/otel_collector.sh stop    # SIGTERM the pid, falls back to SIGKILL
#
# Env (all optional):
#   OC_OTEL_DATA_DIR  Directory for config + trace + pid + log files.
#                     Default: $SCRATCH/oc-eval/otel.
#   OC_OTEL_PORT      OTLP/HTTP listen port. Default: 4318. Must match
#                     frontend/openclaw/state/openclaw.json: diagnostics.otel.endpoint.
#   OC_OTEL_SIF       Path to the otelcol-contrib .sif. Default:
#                     $SCRATCH/sif_images/otelcol-contrib.sif.
#                     Pull on a network-equipped node before submitting:
#                       singularity pull $OC_OTEL_SIF \
#                           docker://otel/opentelemetry-collector-contrib:latest
#   OC_OTEL_DOCKER    Source image. Default:
#                     docker://otel/opentelemetry-collector-contrib:latest.

set -uo pipefail

USER_NAME="${USER:-$(whoami)}"
SCRATCH="${SCRATCH:-/scratch/users/ntu/$USER_NAME}"

DATA_DIR="${OC_OTEL_DATA_DIR:-$SCRATCH/oc-eval/otel}"
PORT="${OC_OTEL_PORT:-4318}"
SIF="${OC_OTEL_SIF:-$SCRATCH/sif_images/otelcol-contrib.sif}"
DOCKER="${OC_OTEL_DOCKER:-docker://otel/opentelemetry-collector-contrib:latest}"

PID_FILE="$DATA_DIR/otelcol.pid"
LOG_FILE="$DATA_DIR/otelcol.log"
CONFIG_FILE="$DATA_DIR/otelcol.yaml"
TRACE_FILE="$DATA_DIR/otel-traces.jsonl"

LOG() { echo "[$(date -u +%FT%TZ)] otel_collector: $*"; }

ensure_sif() {
    if [[ -f "$SIF" ]]; then
        return 0
    fi
    LOG "pulling $DOCKER -> $SIF (one-time; needs network)"
    mkdir -p "$(dirname "$SIF")"
    if ! singularity pull --name "$(basename "$SIF")" \
            --dir "$(dirname "$SIF")" "$DOCKER" >&2; then
        LOG "ERROR: singularity pull failed; pre-pull on a login node and"
        LOG "       set OC_OTEL_SIF to its path."
        return 1
    fi
}

write_config() {
    cat > "$CONFIG_FILE" <<YAML
# Generated by pbs/otel_collector.sh — overwritten on every start.
receivers:
  otlp:
    protocols:
      http:
        endpoint: 127.0.0.1:$PORT

exporters:
  file:
    path: $TRACE_FILE
    # No rotation: per-job runs are minutes long, the trace file stays small.

service:
  telemetry:
    logs:
      level: warn
  pipelines:
    traces:
      receivers: [otlp]
      exporters: [file]
    metrics:
      receivers: [otlp]
      exporters: [file]
    logs:
      receivers: [otlp]
      exporters: [file]
YAML
    LOG "wrote config -> $CONFIG_FILE"
}

start_collector() {
    mkdir -p "$DATA_DIR"

    # Idempotent: if a previous start left a live process, return success.
    if [[ -f "$PID_FILE" ]]; then
        local old_pid
        old_pid=$(cat "$PID_FILE" 2>/dev/null || true)
        if [[ -n "$old_pid" ]] && kill -0 "$old_pid" 2>/dev/null; then
            LOG "already running (pid=$old_pid)"
            return 0
        fi
        rm -f "$PID_FILE"
    fi

    write_config
    if ! ensure_sif; then
        return 1
    fi

    LOG "starting otelcol-contrib (port=$PORT, traces=$TRACE_FILE)"
    # singularity run executes the image's runscript (= otelcol-contrib);
    # bind DATA_DIR at the same path so the absolute file: path in the
    # config resolves inside the container.
    setsid singularity run \
        --bind "$DATA_DIR:$DATA_DIR:rw" \
        "$SIF" --config "$CONFIG_FILE" \
        > "$LOG_FILE" 2>&1 &
    local pid=$!
    echo "$pid" > "$PID_FILE"

    # Poll readiness via bash /dev/tcp — avoids needing nc on the host.
    local deadline=$((SECONDS + 30))
    while (( SECONDS < deadline )); do
        if (echo > /dev/tcp/127.0.0.1/"$PORT") 2>/dev/null; then
            LOG "ready on 127.0.0.1:$PORT (pid=$pid, log=$LOG_FILE)"
            return 0
        fi
        if ! kill -0 "$pid" 2>/dev/null; then
            LOG "ERROR: collector exited during startup; tail of log:"
            tail -30 "$LOG_FILE" 2>/dev/null || true
            rm -f "$PID_FILE"
            return 1
        fi
        sleep 1
    done

    LOG "ERROR: collector did not become ready in 30s"
    tail -30 "$LOG_FILE" 2>/dev/null || true
    kill -TERM "$pid" 2>/dev/null || true
    rm -f "$PID_FILE"
    return 1
}

stop_collector() {
    if [[ ! -f "$PID_FILE" ]]; then
        LOG "no pid file at $PID_FILE; nothing to stop"
        return 0
    fi
    local pid
    pid=$(cat "$PID_FILE" 2>/dev/null || true)
    if [[ -z "$pid" ]]; then
        rm -f "$PID_FILE"
        return 0
    fi

    if kill -0 "$pid" 2>/dev/null; then
        LOG "stopping pid=$pid (SIGTERM)"
        kill -TERM "$pid" 2>/dev/null || true
        # otelcol flushes the file exporter on shutdown — give it a moment.
        local i
        for i in $(seq 1 20); do
            sleep 0.5
            kill -0 "$pid" 2>/dev/null || break
        done
        if kill -0 "$pid" 2>/dev/null; then
            LOG "  still alive after 10s; SIGKILL"
            kill -KILL "$pid" 2>/dev/null || true
        fi
    fi
    rm -f "$PID_FILE"
}

mode="${1:-}"
case "$mode" in
    start) start_collector ;;
    stop)  stop_collector ;;
    "")    echo "usage: $0 {start|stop}" >&2; exit 2 ;;
    *)     echo "unknown mode: $mode" >&2; exit 2 ;;
esac
